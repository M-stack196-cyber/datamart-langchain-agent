@router.post(
    "/api/admin/handoff/{conversation_id}/claim",
    dependencies=[Depends(require_admin)],
)
def claim_handoff(
    conversation_id: str,
    db: Session = Depends(get_db),
):
    username = get_settings().admin_username

    session = (
        db.query(HandoffSession)
        .filter(HandoffSession.conversation_id == conversation_id)
        .with_for_update()
        .first()
    )

    if not session:
        db.rollback()
        raise HTTPException(404, "Handoff conversation not found")

    if session.mode == "human":
        if session.assigned_to == username:
            db.rollback()
            return {
                "conversation_id": conversation_id,
                "mode": "human",
                "assigned_to": username,
                "already_claimed": True,
            }
        db.rollback()
        raise HTTPException(409, "Chat already claimed")

    if session.mode != "pending_human":
        db.rollback()
        raise HTTPException(409, "Chat is not waiting for a team member")

    session.mode = "human"
    session.assigned_to = username
    session.claimed_at = datetime.now(timezone.utc)

    request = (
        db.query(HandoffRequest)
        .filter(
            HandoffRequest.conversation_id == conversation_id,
            HandoffRequest.status == "pending",
        )
        .order_by(HandoffRequest.id.desc())
        .first()
    )
    if request:
        request.status = "claimed"

    db.add(
        ConversationMessage(
            conversation_id=conversation_id,
            role="system",
            content=f"{username} from Datamart has joined the live chat.",
        )
    )
    db.commit()

    return {
        "conversation_id": conversation_id,
        "mode": "human",
        "assigned_to": username,
        "already_claimed": False,
    }


