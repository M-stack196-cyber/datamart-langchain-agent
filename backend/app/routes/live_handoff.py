from datetime import datetime, timezone

from fastapi import APIRouter, Depends, HTTPException, Query
from pydantic import BaseModel, Field
from sqlalchemy.orm import Session

from app.auth import require_admin
from app.config import get_settings
from app.db.models import (
    ConversationMessage,
    HandoffRequest,
    HandoffSession,
)
from app.db.session import get_db


router = APIRouter(tags=["live-handoff"])


class AdminMessageCreate(BaseModel):
    message: str = Field(min_length=1, max_length=8000)


@router.get("/api/chat/{conversation_id}/history")
def public_chat_history(
    conversation_id: str,
    db: Session = Depends(get_db),
):
    """
    Restore the visitor's full conversation after refresh/navigation.
    Conversation IDs are UUID-style opaque identifiers generated by the client/backend.
    """
    rows = (
        db.query(ConversationMessage)
        .filter(ConversationMessage.conversation_id == conversation_id)
        .order_by(ConversationMessage.id.asc())
        .all()
    )

    return {
        "conversation_id": conversation_id,
        "messages": [
            {
                "id": row.id,
                "role": row.role,
                "content": row.content,
                "created_at": row.created_at,
            }
            for row in rows
        ],
    }


@router.get("/api/chat/{conversation_id}/live")
def public_live_state(
    conversation_id: str,
    after_id: int = Query(default=0, ge=0),
    db: Session = Depends(get_db),
):
    session = (
        db.query(HandoffSession)
        .filter(HandoffSession.conversation_id == conversation_id)
        .first()
    )

    mode = session.mode if session else "bot"
    assigned_to = session.assigned_to if session else None

    rows = (
        db.query(ConversationMessage)
        .filter(
            ConversationMessage.conversation_id == conversation_id,
            ConversationMessage.id > after_id,
            ConversationMessage.role.in_(["agent", "system"]),
        )
        .order_by(ConversationMessage.id.asc())
        .all()
    )

    latest_row = (
        db.query(ConversationMessage)
        .filter(ConversationMessage.conversation_id == conversation_id)
        .order_by(ConversationMessage.id.desc())
        .first()
    )

    return {
        "mode": mode,
        "assigned_to": assigned_to,
        "last_message_id": latest_row.id if latest_row else after_id,
        "messages": [
            {
                "id": row.id,
                "role": row.role,
                "content": row.content,
                "created_at": row.created_at,
            }
            for row in rows
        ],
    }


