@router.post(
    "/api/admin/handoff/{conversation_id}/message",
    dependencies=[Depends(require_admin)],
)
def admin_handoff_message(
    conversation_id: str,
    payload: AdminMessageCreate,
    db: Session = Depends(get_db),
):
    username = get_settings().admin_username

    session = (
        db.query(HandoffSession)
        .filter(HandoffSession.conversation_id == conversation_id)
        .first()
    )

    if not session:
        raise HTTPException(404, "Handoff conversation not found")

    if session.mode != "human" or session.assigned_to != username:
        raise HTTPException(403, "You have not claimed this chat")

    row = ConversationMessage(
        conversation_id=conversation_id,
        role="agent",
        content=payload.message.strip(),
    )
    db.add(row)
    db.commit()
    db.refresh(row)

    return {
        "id": row.id,
        "role": row.role,
        "content": row.content,
        "created_at": row.created_at,
    }


@router.post(
    "/api/admin/handoff/{conversation_id}/end",
    dependencies=[Depends(require_admin)],
)
def end_handoff(
    conversation_id: str,
    db: Session = Depends(get_db),
):
    username = get_settings().admin_username

    session = (
        db.query(HandoffSession)
        .filter(HandoffSession.conversation_id == conversation_id)
        .with_for_update()
        .first()
    )

    if not session:
        db.rollback()
        raise HTTPException(404, "Handoff conversation not found")

    if session.mode == "closed":
        db.rollback()
        return {"mode": "closed", "already_closed": True}

    if session.mode != "human" or session.assigned_to != username:
        db.rollback()
        raise HTTPException(403, "You are not assigned to this chat")

    session.mode = "closed"
    session.closed_at = datetime.now(timezone.utc)

    request = (
        db.query(HandoffRequest)
        .filter(HandoffRequest.conversation_id == conversation_id)
        .order_by(HandoffRequest.id.desc())
        .first()
    )
    if request:
        request.status = "closed"

    db.add(
        ConversationMessage(
            conversation_id=conversation_id,
            role="system",
            content=(
                "This live chat has ended. You can continue chatting with "
                "Datamart's AI assistant by sending a new message."
            ),
        )
    )
    db.commit()

    return {"mode": "closed", "already_closed": False}
